-- Fresh-project foundation for the legacy bigint CRM schema.
-- Later migrations add organizations, stricter RLS and newer domain columns.

CREATE TABLE IF NOT EXISTS public.leads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    nome text,
    empresa text,
    telefone text,
    email text,
    canal text NOT NULL DEFAULT 'whatsapp',
    status_pipeline text NOT NULL DEFAULT 'novo_lead',
    valor_estimado numeric,
    consumo_kwh numeric,
    observacoes text,
    tipo_cliente text,
    endereco text,
    cidade text,
    cep text,
    phone_e164 text,
    instance_name text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_leads_user_id
ON public.leads(user_id);

CREATE INDEX IF NOT EXISTS idx_leads_phone_e164
ON public.leads(phone_e164);

CREATE TABLE IF NOT EXISTS public.whatsapp_instances (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    instance_name text NOT NULL,
    instance_token text,
    status text NOT NULL DEFAULT 'disconnected',
    phone_number text,
    qr_code text,
    connected_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    is_active boolean NOT NULL DEFAULT true,
    ai_enabled boolean DEFAULT true,
    display_name text
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_whatsapp_instances_user_instance
ON public.whatsapp_instances(user_id, instance_name);

CREATE TABLE IF NOT EXISTS public.interacoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
    tipo text NOT NULL,
    mensagem text,
    created_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    wa_message_id text,
    remote_jid text,
    reply_to_message_id text,
    reply_to_interacao_id bigint,
    reply_preview text,
    reply_type text,
    mime_type text,
    file_name text,
    file_size bigint,
    send_mode text,
    fallback_from text,
    phone_e164 text,
    attachment_url text,
    attachment_type text,
    attachment_mimetype text,
    attachment_name text,
    attachment_size bigint,
    attachment_ready boolean DEFAULT true,
    attachment_error boolean DEFAULT false,
    attachment_error_message text,
    wa_from_me boolean DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_interacoes_lead_created
ON public.interacoes(lead_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_interacoes_remote_jid
ON public.interacoes(remote_jid);

CREATE INDEX IF NOT EXISTS idx_interacoes_phone_e164
ON public.interacoes(phone_e164);

CREATE TABLE IF NOT EXISTS public.comentarios_leads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
    texto text NOT NULL,
    autor text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    comment_type text,
    date_bucket date
);

CREATE INDEX IF NOT EXISTS idx_comentarios_leads_lead_created
ON public.comentarios_leads(lead_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.propostas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint REFERENCES public.leads(id) ON DELETE CASCADE,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    valor_projeto numeric,
    consumo_kwh numeric,
    potencia_kw numeric,
    paineis_qtd integer,
    economia_mensal numeric,
    payback_anos numeric,
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_propostas_lead_created
ON public.propostas(lead_id, created_at DESC);

